#!/usr/bin/env python3
"""Generate the Zed task templates in tasks/.

Zed tasks run a command through the user's shell, and a fresh install has no
`pypilot` on PATH: the Zed extension downloads its own copy into Zed's
extension work dir, which only the language server knows about. So every task
looks for `pypilot` on PATH first, then for the copy the extension downloaded.
That lookup differs between PowerShell (Windows) and sh (macOS, Linux), and a
Zed tasks file cannot branch on the OS, so there is one template per OS:

    tasks/windows.json       PowerShell, Zed's default shell on Windows
    tasks/macos-linux.json   sh -c, whatever the user's own shell is

Usage:
    python scripts/gen_zed_tasks.py            write both files
    python scripts/gen_zed_tasks.py --check    exit 1 if they are out of date
    python scripts/gen_zed_tasks.py --self-test
        run the lookups with pypilot hidden from PATH and a fake extension copy
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks"

# (label, pypilot arguments, saves files first)
COMMANDS = [
    ("pypilot: fix environment (only what doctor found)", ["doctor", "--fix"], True),
    ("pypilot: set up environment (full bootstrap)", ["setup"], True),
    ("pypilot: show details (doctor report)", ["doctor"], False),
    ("pypilot: explain python range (what blocks each version)", ["explain"], False),
    ("pypilot: fix python version", ["fix", "python"], True),
    ("pypilot: fix cuda (re-pin torch/tensorflow to the driver)", ["fix", "cuda"], True),
    ("pypilot: fix requirements (apply doctor's requirement edits)", ["fix", "requirements"], True),
    ("pypilot: update data (refresh bundled tables)", ["update-data"], False),
    ("pypilot: migrate conda to pyproject.toml", ["migrate-conda"], True),
    ("pypilot: preview migration to pixi (pixi.toml)", ["migrate-to-pixi"], False),
    ("pypilot: migrate to pixi (write pixi.toml and install)", ["migrate-to-pixi", "--write", "--install"], True),
    ("pypilot: install pixi", ["install-pixi"], False),
]

MISSING = (
    "PyPilot could not find the pypilot command. Open a Python file so the Zed "
    "extension downloads it, or install it with: pip install pypilot-cli"
)

WORK_DIR_WIN = r"Zed\extensions\work\pypilot-language-server\pypilot-*\pypilot.exe"


def powershell(args):
    """The PowerShell command for one task.

    Zed on Windows runs a task as `pwsh -C '<command>'`, so the command must not
    contain a single quote. Write-Host gets the message as bare words for the
    same reason, so the message drops its comma and colon.
    """
    words = MISSING.replace(",", "").replace(":", "")
    return (
        "$p = (Get-Command pypilot -CommandType Application -ErrorAction SilentlyContinue"
        " | Select-Object -First 1).Source; "
        f"if (-not $p) {{ $p = Get-ChildItem -Path (Join-Path $env:LOCALAPPDATA {WORK_DIR_WIN})"
        " -ErrorAction SilentlyContinue | Sort-Object LastWriteTime -Descending"
        " | Select-Object -First 1 -ExpandProperty FullName }; "
        f"if (-not $p) {{ Write-Host {words}; exit 1 }}; "
        f"& $p {' '.join(args)}; exit $LASTEXITCODE"
    )


# Run as `sh -c SH pypilot <args>`: one snippet for every task, and it works
# whatever the user's login shell is (fish included). The extension's work dir
# is under Zed's data dir: XDG on Linux, Application Support on macOS, and the
# Flatpak sandbox's data dir for the Flatpak build.
SH = (
    'p=$(command -v pypilot 2>/dev/null); '
    'if [ -z "$p" ]; then '
    'for d in "${XDG_DATA_HOME:-$HOME/.local/share}/zed" '
    '"$HOME/Library/Application Support/Zed" '
    '"$HOME/.var/app/dev.zed.Zed/data/zed"; do '
    'for f in "$d"/extensions/work/pypilot-language-server/pypilot-*/pypilot; do '
    '[ -x "$f" ] && p=$f; done; done; fi; '
    f'if [ -z "$p" ]; then echo "{MISSING}" >&2; exit 1; fi; '
    'exec "$p" "$@"'
)

HEADER = """\
// PyPilot tasks for Zed on {os_name}. Generated by scripts/gen_zed_tasks.py;
// edit that script, not this file.
//
// Copy into your global tasks file ({global_path}) or into a
// project's .zed/tasks.json, then run them with `task: spawn`.
//
// Each task runs the `pypilot` on your PATH if there is one, and otherwise
// the copy the PyPilot Zed extension downloaded for its language server, so
// nothing else needs installing. Open a Python file once so the extension
// has downloaded it.
//
// The fix environment task runs `pypilot doctor --fix`, the same targeted fix
// as the editor's "Fix environment" button; show details runs `pypilot doctor`.
// No task passes `--path`: Zed runs tasks in the worktree root, so paths with
// spaces are never split.
{extra}"""

WINDOWS_EXTRA = """\
//
// These commands are PowerShell, Zed's default shell on Windows. If you set
// another shell in Zed, use PowerShell for tasks. If spawning a task fails
// with "os error 193 (%1 is not a valid Win32 application)", Zed cannot start
// a PowerShell installed from the Microsoft Store; point it at a real
// executable in settings.json:
//   "terminal": { "shell": { "with_arguments": {
//     "program": "C:\\\\Windows\\\\System32\\\\WindowsPowerShell\\\\v1.0\\\\powershell.exe",
//     "args": ["-NoProfile"] } } }
"""


def task(label, saves, command, args):
    t = {"label": label, "command": command}
    if args:
        t["args"] = args
    t.update({
        "cwd": "$ZED_WORKTREE_ROOT",
        "use_new_terminal": False,
        "allow_concurrent_runs": False,
    })
    if saves:
        t["save"] = "all"
    t["reveal"] = "always"
    return t


def render():
    windows = [task(label, saves, powershell(args), None) for label, args, saves in COMMANDS]
    unix = [task(label, saves, "sh", ["-c", SH, "pypilot", *args]) for label, args, saves in COMMANDS]
    return {
        "windows.json": HEADER.format(
            os_name="Windows", global_path=r"%APPDATA%\Zed\tasks.json", extra=WINDOWS_EXTRA
        ) + json.dumps(windows, indent=2) + "\n",
        "macos-linux.json": HEADER.format(
            os_name="macOS and Linux", global_path="~/.config/zed/tasks.json", extra=""
        ) + json.dumps(unix, indent=2) + "\n",
    }


def write():
    TASKS.mkdir(exist_ok=True)
    for name, text in render().items():
        (TASKS / name).write_bytes(text.encode("utf-8"))
        print(f"wrote tasks/{name}")


def check():
    stale = [n for n, text in render().items()
             if not (TASKS / n).exists() or (TASKS / n).read_bytes() != text.encode("utf-8")]
    for n in stale:
        print(f"tasks/{n} is out of date; run python scripts/gen_zed_tasks.py")
    return 1 if stale else 0


def self_test():
    """Run both lookups with pypilot hidden from PATH."""
    assert "'" not in SH and all("'" not in powershell(a) for _, a, _ in COMMANDS), \
        "a single quote would break Zed's quoting"
    failures = 0

    def run(label, cmd, env, want_ok, want_text):
        nonlocal failures
        r = subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=120)
        out = r.stdout + r.stderr
        ok = (r.returncode == 0) == want_ok and want_text in out
        failures += not ok
        print(f"{'ok  ' if ok else 'FAIL'} {label} (exit {r.returncode}): {out.strip()[:100]}")

    def clean_path():
        return os.pathsep.join(
            d for d in os.environ.get("PATH", "").split(os.pathsep)
            if d and not any((Path(d) / n).exists() for n in ("pypilot", "pypilot.exe"))
        )

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        if os.name == "nt":
            real = shutil.which("pypilot")
            fake = None
        else:
            # A stand-in for the downloaded helper: prints its arguments.
            fake = tmp / "fake-pypilot"
            fake.write_text('#!/bin/sh\necho "fake pypilot $*"\n')
            fake.chmod(0o755)
            real = None
        source = fake or real

        sh = shutil.which("sh")
        if sh and os.name != "nt":
            home = tmp / "home dir"
            d = home / ".local/share/zed/extensions/work/pypilot-language-server/pypilot-v9.9.9"
            d.mkdir(parents=True)
            shutil.copy(source, d / "pypilot")
            env = dict(os.environ, PATH=clean_path(), HOME=str(home))
            env.pop("XDG_DATA_HOME", None)
            run("sh: the extension's copy", [sh, "-c", SH, "pypilot", "doctor", "--fix"], env, True,
                "doctor --fix" if fake else "")
            run("sh: nothing found", [sh, "-c", SH, "pypilot", "doctor"],
                dict(env, HOME=str(tmp / "nobody")), False, "could not find the pypilot command")

        pwsh = shutil.which("pwsh") or shutil.which("powershell")
        if pwsh and source:
            local = tmp / "App Data Local"
            d = local / "Zed/extensions/work/pypilot-language-server/pypilot-v9.9.9"
            d.mkdir(parents=True)
            shutil.copy(source, d / "pypilot.exe")
            env = dict(os.environ, PATH=clean_path(), LOCALAPPDATA=str(local))
            args = ["doctor", "--fix"] if fake else ["--version"]
            run("powershell: the extension's copy", [pwsh, "-NoProfile", "-C", powershell(args)], env, True,
                "doctor --fix" if fake else "pypilot")
            run("powershell: nothing found", [pwsh, "-NoProfile", "-C", powershell(["doctor"])],
                dict(env, LOCALAPPDATA=str(tmp / "nothing")), False, "could not find the pypilot command")
    if failures:
        print(f"{failures} self-test(s) failed")
    return 1 if failures else 0


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        sys.exit(self_test())
    if "--check" in sys.argv:
        sys.exit(check())
    write()
